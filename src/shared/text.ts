/** 繁体转简体（逐字，不做词组级转换，够用且不会转错）。 */
export function toSimplified(input: string): string {
  let out = '';
  for (const char of input) out += TRAD_TO_SIMP.get(char) ?? char;
  return out;
}

/** 全角字母数字和空格 → 半角。 */
export function toHalfWidth(input: string): string {
  let out = '';
  for (const char of input) {
    const code = char.charCodeAt(0);
    if (code === 0x3000) out += ' ';
    else if (code >= 0xff01 && code <= 0xff5e) out += String.fromCharCode(code - 0xfee0);
    else out += char;
  }
  return out;
}

/** 去掉拉丁字母的变音符号：Pokémon → Pokemon。 */
export function stripDiacritics(input: string): string {
  return input.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

const SEASON_PATTERNS: RegExp[] = [
  // 中文：第一季 / 第 2 季 / 第二部
  /\s*第\s*([0-9]+|[一二三四五六七八九十]+)\s*[季部]\s*$/u,
  // 英文：Season 2 / Series 2 / Part 2 / Book 2，前面可能有冒号或破折号
  /\s*[:：\-–—]?\s*(?:season|series|part|book|chapter)\s*([0-9]+|[ivxlc]+)\s*$/iu,
  // 紧凑写法：S2（前面必须有空格，避免误伤 "Kids S" 这种）
  /\s+s\s?([0-9]{1,2})\s*$/iu,
];

const CJK_NUMERALS: Record<string, number> = {
  一: 1, 二: 2, 兩: 2, 两: 2, 三: 3, 四: 4, 五: 5,
  六: 6, 七: 7, 八: 8, 九: 9, 十: 10,
};

const ROMAN_NUMERALS: Record<string, number> = {
  i: 1, ii: 2, iii: 3, iv: 4, v: 5, vi: 6, vii: 7, viii: 8, ix: 9, x: 10,
};

function parseSeasonNumber(token: string): number | undefined {
  const trimmed = token.trim();
  if (/^[0-9]+$/.test(trimmed)) {
    const value = Number.parseInt(trimmed, 10);
    return value > 0 && value < 100 ? value : undefined;
  }
  // 十一 / 十二 …
  const cjkMatch = /^十([一二三四五六七八九])$/u.exec(trimmed);
  if (cjkMatch) return 10 + (CJK_NUMERALS[cjkMatch[1]!] ?? 0);
  if (CJK_NUMERALS[trimmed] !== undefined) return CJK_NUMERALS[trimmed];
  const roman = ROMAN_NUMERALS[trimmed.toLowerCase()];
  return roman;
}

export interface SeasonSplit {
  /** 去掉季数后缀后的主标题。 */
  base: string;
  /** 解析到的季数；没有季数后缀时为 undefined。 */
  season?: number;
}

/**
 * 把 "怪奇物语 第四季" / "Stranger Things: Season 4" 拆成主标题和季数。
 *
 * Netflix 的剧集卡片通常只给剧名，而豆瓣把每一季登记成独立条目，所以
 * 匹配时必须先把两边都拆开，再单独比较季数。
 */
export function splitSeason(title: string): SeasonSplit {
  let base = title.trim();
  for (const pattern of SEASON_PATTERNS) {
    const match = pattern.exec(base);
    if (!match) continue;
    const season = parseSeasonNumber(match[1]!);
    if (season === undefined) continue;
    return { base: base.slice(0, match.index).trim(), season };
  }
  return { base };
}

/**
 * 归一化到用于比较的形式：小写、半角、简体、无变音符号、无标点空格。
 *
 * 注意这里会把空格一并去掉，所以归一化后的串只适合做「相等 / 包含」判断，
 * 分词相似度请用 tokenize。
 */
export function normalizeTitle(title: string): string {
  const unified = stripDiacritics(toSimplified(toHalfWidth(title))).toLowerCase();
  return unified
    .replace(/&/g, 'and')
    // 保留中日韩文字、拉丁字母和数字，其余（标点、空格、emoji）全部丢掉
    .replace(/[^\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}a-z0-9]/gu, '');
}

/** 拉丁标题按词切分，用于计算词级相似度。中文标题会退化成单字序列。 */
export function tokenize(title: string): string[] {
  const unified = stripDiacritics(toSimplified(toHalfWidth(title))).toLowerCase().replace(/&/g, ' and ');
  const tokens: string[] = [];
  for (const raw of unified.split(/[^\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}a-z0-9]+/u)) {
    if (!raw) continue;
    // 连续汉字拆成单字，让「中文标题」也能算重合度
    if (/^[\p{Script=Han}]+$/u.test(raw)) tokens.push(...raw);
    else tokens.push(raw);
  }
  return tokens;
}

/** 两个词集合的 Dice 系数，范围 0–1。 */
export function diceCoefficient(a: readonly string[], b: readonly string[]): number {
  if (a.length === 0 || b.length === 0) return 0;
  const counts = new Map<string, number>();
  for (const token of a) counts.set(token, (counts.get(token) ?? 0) + 1);
  let overlap = 0;
  for (const token of b) {
    const remaining = counts.get(token) ?? 0;
    if (remaining > 0) {
      overlap += 1;
      counts.set(token, remaining - 1);
    }
  }
  return (2 * overlap) / (a.length + b.length);
}

/**
 * 标题里是否含 CJK 字符（中日韩统一表意文字及其扩展区、假名、谚文）。
 */
export function hasCJK(text: string): boolean {
  return /[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uac00-\ud7af]/.test(text);
}

/** 标题里是否含拉丁字母。 */
export function hasLatin(text: string): boolean {
  return /[A-Za-z]/.test(text);
}

/**
 * 两个标题的书写系统能不能放在一起比相似度。
 *
 * 用途：IMDb 的下拉建议接口认得中文片名（查「鱿鱼游戏」能命中），但**返回的
 * 标题是英文**（"Squid Game"）。拿这两个串去算词重合必然是 0 分，整条结果
 * 就被匹配器扔掉了 —— 搜索明明成功了，用户却一个 IMDb 分都看不到。
 * 所以在打分之前要先判断：这两个名字压根不在同一个书写系统里，
 * 相似度这个信号本身就不适用，得换别的依据。
 */
export function comparableScripts(a: string, b: string): boolean {
  // 一方是纯 CJK、另一方完全没有 CJK —— 没有可比的字面。
  if (hasCJK(a) && !hasCJK(b) && !hasLatin(a)) return false;
  if (hasCJK(b) && !hasCJK(a) && !hasLatin(b)) return false;
  return true;
}
